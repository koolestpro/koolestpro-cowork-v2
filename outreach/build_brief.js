#!/usr/bin/env node
// Compiles outreach/brief-ai.md into outreach/gmail-sender/Brief.gs (paste it into Apps Script as a second file).
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, 'brief-ai.md'), 'utf8');
const parts = {};
src.split(/^## /m).slice(1).forEach(block => {
  const nl = block.indexOf('\n');
  parts[block.slice(0, nl).trim().toLowerCase()] = block.slice(nl + 1).trim();
});
const need = ['core', 'region:ng', 'region:uk', 'region:us', 'region:eu', 'region:other'];
need.forEach(k => { if (!parts[k]) throw new Error('brief-ai.md missing section: ' + k); });
if (/—/.test(src)) throw new Error('brief-ai.md contains an em dash');
const out = '// GENERATED by outreach/build_brief.js from outreach/brief-ai.md. Do not edit here; edit brief-ai.md and rebuild.\n' +
  'const BRIEF_ = ' + JSON.stringify({
    core: parts['core'],
    regions: { ng: parts['region:ng'], uk: parts['region:uk'], us: parts['region:us'], eu: parts['region:eu'], other: parts['region:other'] },
  }, null, 2) + ';\n';
fs.writeFileSync(path.join(__dirname, 'gmail-sender', 'Brief.gs'), out);
console.log('Brief.gs written,', out.length, 'chars');
